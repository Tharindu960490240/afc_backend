// The signed-in agent's own application (for agents invited by the college).
const router = require("express").Router();
const ctrl = require("../controllers/agentApplicationController");
const docs = require("../controllers/comsDocumentsController");
const validate = require("../middlewares/validate");
const limits = require("../middlewares/rateLimit");
const { authenticate, requireRole } = require("../middlewares/authenticate");
const s = require("../validators/schemas");

router.use(authenticate, requireRole("agent"));
router.get("/", ctrl.show);
router.post("/", limits.sensitive, validate(s.submitApplication), ctrl.submit);
router.get("/induction", ctrl.induction);
const oi = require("../controllers/onlineInductionController");
router.get("/online-induction", oi.mine);
router.post("/online-induction/modules/:id/complete", validate(s.idOnly, "params"), oi.completeModule);
router.post("/online-induction/acknowledge", limits.sensitive, validate(s.ppAcknowledge), oi.acknowledge);
router.get("/materials", oi.myMaterials);
router.get("/materials/:id/download", limits.sensitive, validate(s.idOnly, "params"), oi.myMaterialDownload);
const crm = require("../controllers/crmController");
router.get("/leads", crm.myLeads);
router.post("/leads", validate(s.leadBody), crm.addLead);
router.patch("/leads/:id", validate(s.idOnly, "params"), validate(s.leadBody), crm.updateLead);
router.get("/communications", crm.myCommunications);
router.get("/certificate", docs.mineCertificateStatus);
router.get("/certificate/download", limits.sensitive, docs.mineCertificate);
router.get("/documents", docs.mine);
router.post("/documents", limits.sensitive, validate(s.agentDocument), docs.mineUpload);
router.post("/documents/:docId/delete", validate(s.documentParams.omit({ id: true }), "params"), docs.mineRemove);
router.get("/documents/:docId/download", limits.sensitive, validate(s.documentParams.omit({ id: true }), "params"), docs.mineDownload);
module.exports = router;
